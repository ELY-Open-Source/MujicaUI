func MessagingDate(c *ui.Context, date time.Time, key string) string {
	weekday := Msg(c, "calendar.weekday_long_"+strconv.Itoa(int(date.Weekday())))
	return strings.ReplaceAll(date.Format(Msg(c, key)), "{weekday}", weekday)
}
